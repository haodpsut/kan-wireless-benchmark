#!/usr/bin/env python3
"""Tiem loi vao mot bai HOP LE roi doi cong phai bat.

Luat cua nha: cong khong co chung duong tinh thi khong tinh la cong. Moi cong o
day co it nhat mot ca PHAI BAT va mot ca KHONG DUOC BAT OAN, vi siet cong ma
khong do bao dong gia thi chi doi mot loi lay mot loi khac.
"""
import os, re, shutil, subprocess, sys, tempfile, random

GOC = os.path.dirname(os.path.abspath(__file__))
XANH, DO, CHAN = 0, 1, 2
TEN = {XANH: "XANH", DO: "DO", CHAN: "CHAN"}

TU = ("the predicate uses published orbital elements and a geometric visibility test while the "
      "learned model consumes the same elements and returns a binary label we therefore compare "
      "them on identical inputs and report the gap under stale ephemeris across three "
      "constellations with independent reference data and a null condition that keeps the previous "
      "state so that any reported advantage must exceed what persistence alone would give under "
      "the same budget and the same evaluation window for every satellite pair we examine").split()


def van_day(so_tu, hat=7):
    r = random.Random(hat)
    ra, n = [], 0
    while n < so_tu:
        cau = " ".join(r.choice(TU) for _ in range(r.randint(14, 24)))
        ra.append(cau[0].upper() + cau[1:] + ".")
        n += cau.count(" ") + 1
    return " ".join(ra)


def lam_bai_hop_le(d):
    """Dung mot bai Elsevier DAY DU trong thu muc d, moi cong phai XANH."""
    shutil.copytree(GOC, d, dirs_exist_ok=True,
                    ignore=shutil.ignore_patterns("main.pdf", "main.aux", "main.log",
                                                  "main.fls", "main.fdb_latexmk", "main.out",
                                                  "main.bbl", "main.blg", "__pycache__"))
    s = open(os.path.join(d, "main.tex"), encoding="utf-8").read()
    s = s.replace("TIEU DE BAI", "Does Inter Satellite Link Prediction Need Learning")
    s = s.replace("Thay doan nay bang tom tat that. Neu con cau nay thi cong c3 chan.\n"
                  "Tom tat phai neu doi tuong, phep do, con so chinh, va ket luan, moi thu mot cau.\n"
                  "Khong dung em-dash. Moi con so trong day phai la macro tu so.tex, vi du\n"
                  "trung vi sai so ban tin la \\TLEmed{} km.",
                  van_day(160, 3) + " The median bulletin error is \\TLEmed{} km and the geometric "
                  "predicate reaches an agreement of \\Fmotvitu{} under the same budget.")
    s = s.replace("tu khoa mot \\sep tu khoa hai \\sep tu khoa ba \\sep tu khoa bon",
                  "satellite networks \\sep link prediction \\sep evaluation \\sep reproducibility")
    s = s.replace("DIA-CHI-KHO", "github.com/haodpsut/leo-link-prediction")
    open(os.path.join(d, "main.tex"), "w", encoding="utf-8").write(s)

    phan = sorted(os.listdir(os.path.join(d, "phan")))
    moi_muc = 8300 // len(phan) + 40
    for i, f in enumerate(phan):
        p = os.path.join(d, "phan", f)
        t = re.sub(r"^[0-9]*-", "", f[:-4]).replace("-", " ")
        open(p, "w", encoding="utf-8").write(
            "\\section{%s}\n%s\n" % (t.title(), van_day(moi_muc, 11 + i)))

    open(os.path.join(d, "highlights.tex"), "w", encoding="utf-8").write(
        "\\begin{itemize}\n"
        "\\item A geometric predicate matches learned link prediction on identical inputs.\n"
        "\\item The gap survives stale ephemeris across three real constellations.\n"
        "\\item Labels generated by the predicate make the reported accuracy circular.\n"
        "\\end{itemize}\n")
    return d


def dich(d):
    subprocess.run(["latexmk", "-pdf", "-interaction=nonstopmode", "-halt-on-error", "main.tex"],
                   cwd=d, capture_output=True)
    return os.path.isfile(os.path.join(d, "main.pdf"))


def chay_cong(d, cong, *doi):
    r = subprocess.run([sys.executable, os.path.join("cong", cong), *doi],
                       cwd=d, capture_output=True, text=True)
    return r.returncode, r.stdout


def sua(d, tep, cu, moi):
    p = os.path.join(d, tep)
    s = open(p, encoding="utf-8").read()
    assert cu in s, "khong tim thay %r trong %s" % (cu[:40], tep)
    open(p, "w", encoding="utf-8").write(s.replace(cu, moi, 1))


def rut_abstract(d, cau):
    p = os.path.join(d, "main.tex")
    t = open(p, encoding="utf-8").read()
    t2 = re.sub(r"(\\begin\{abstract\})(.*?)(\\end\{abstract\})",
                lambda m: m.group(1) + "\n" + cau + "\n" + m.group(3), t, flags=re.S)
    assert t2 != t, "khong thay abstract"
    open(p, "w", encoding="utf-8").write(t2)


CA = []


def ca(ten, cong, mong, dung, kiem_them=None, can_pdf=False):
    CA.append((ten, cong, mong, dung, kiem_them, can_pdf))


# ---- c1: so tu
ca("c1 ban day du thi khong bao oan", "c1_dem_tu.py", XANH, lambda d: None)
ca("c1 bat ban qua ngan", "c1_dem_tu.py", DO,
   lambda d: [open(os.path.join(d, "phan", f), "w", encoding="utf-8").write("\\section{X}\nngan.\n")
              for f in os.listdir(os.path.join(d, "phan"))])

# ---- c2: highlights
ca("c2 ban dung thi khong bao oan", "c2_highlights.py", XANH, lambda d: None)
ca("c2 bat gach dai qua 85 ky tu", "c2_highlights.py", DO,
   lambda d: sua(d, "highlights.tex", "A geometric predicate matches learned link prediction on identical inputs.",
                 "A geometric predicate matches learned inter satellite link prediction on exactly identical inputs across every constellation."))
ca("c2 bat so gach sai", "c2_highlights.py", DO,
   lambda d: sua(d, "highlights.tex", "\\end{itemize}",
                 "\\item bon.\n\\item nam.\n\\item sau.\n\\end{itemize}"))

# ---- c3: hien vat
ca("c3 ban day du thi khong bao oan", "c3_hien_vat.py", XANH, lambda d: None)
ca("c3 bat abstract qua ngan", "c3_hien_vat.py", DO,
   lambda d: rut_abstract(d, "Bai nay do mot phep so sanh."))
ca("c3 bat thieu muc san co du lieu", "c3_hien_vat.py", DO,
   lambda d: sua(d, "main.tex", "\\section*{Data availability}", "\\section*{Khong khai}"))
ca("c3 bat van mau con sot", "c3_hien_vat.py", DO,
   lambda d: sua(d, "phan/01-mo-dau.tex", "\\section{Mo Dau}", "\\section{Mo Dau}\nTODO viet lai."))

# ---- c4: em-dash, hai nguon
ca("c4 ban sach thi khong bao oan", "c4_em_dash.py", XANH, lambda d: None, can_pdf=True)
ca("c4 bat --- va BAN IN cung phai thay", "c4_em_dash.py", DO,
   lambda d: sua(d, "phan/02-lien-quan.tex", "\\section{Lien Quan}",
                 "\\section{Lien Quan}\nMot cau --- co dau noi dai --- o giua.\n"),
   kiem_them=lambda ra: ("nguon pdf: 0 em-dash" not in ra and "nguon pdf:" in ra),
   can_pdf=True)
ca("c4 CHAN khi chua co ban in", "c4_em_dash.py", CHAN, lambda d: None, can_pdf=False)

# ---- c5: so go tay
ca("c5 ban chi dung macro thi khong bao oan", "c5_so_go_tay.py", XANH, lambda d: None)
ca("c5 bat so PHAN TRAM go tay", "c5_so_go_tay.py", DO,
   lambda d: sua(d, "phan/04-ket-qua.tex", "\\section{Ket Qua}",
                 "\\section{Ket Qua}\nMo hinh hoc dat do chinh xac 94,3\\% tren bo nay.\n"))
ca("c5 KHONG bat nam thang trong van xuoi", "c5_so_go_tay.py", XANH,
   lambda d: sua(d, "phan/05-ban-luan.tex", "\\section{Ban Luan}",
                 "\\section{Ban Luan}\nBo du lieu duoc cong bo nam 2026 va cap nhat sau do.\n"))


def main():
    dat = 0
    print("tiem %d ca vao mot bai HOP LE\n" % len(CA))
    for ten, cong, mong, dung, kiem_them, can_pdf in CA:
        d = tempfile.mkdtemp(prefix="tiem-")
        try:
            lam_bai_hop_le(d)
            dung(d)
            if can_pdf:
                if not dich(d):
                    print("HONG %s: khong dich duoc ban tiem" % ten)
            ma, ra = chay_cong(d, cong)
            ok = (ma == mong)
            if ok and kiem_them:
                ok = bool(kiem_them(ra))
            print("%-4s %-46s mong %-5s duoc %-5s" % ("DAT" if ok else "HONG", ten,
                                                      TEN[mong], TEN.get(ma, ma)))
            if not ok:
                print(re.sub(r"(?m)^", "         ", ra.strip()))
            dat += ok
        finally:
            shutil.rmtree(d, ignore_errors=True)
    print("\n%d/%d ca DAT" % (dat, len(CA)))
    return 0 if dat == len(CA) else 1


if __name__ == "__main__":
    sys.exit(main())
